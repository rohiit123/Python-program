marks=[45,5,0,12,17,23,18,21]

# To get the length

n=len(marks)
print(f"Length of list = {n}")


# Maximum

maxi=max(marks)
print(f"Maximum marks = {maxi}")

# Minimum

mini=min(marks)
print(f"Minimum marks = {mini}")

# sum

total=sum(marks)
print(f"sum of marks = {total}")

# sort
new_list=sorted(marks)
print(f"New_List = {new_list}")